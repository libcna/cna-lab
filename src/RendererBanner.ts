    public static draw(spriteBatch: SpriteBatch, solidTexture: Texture2D, text: string, viewportWidth: number): void {
        const textUpper = text.toUpperCase();
        const glyphColumns = textUpper.length * 6 - 1;
        let pixelSize = Math.floor((viewportWidth - 48) / glyphColumns);
        if (pixelSize < 1) pixelSize = 1;
        if (pixelSize > 8) pixelSize = 8;

        const textWidth = glyphColumns * pixelSize;
        const textHeight = 7 * pixelSize;
        const textX = Math.floor((viewportWidth - textWidth) / 2);
        const textY = 28;
        const padding = 14;

        // Background banner
        spriteBatch.draw(
            solidTexture,
            { x: textX - padding, y: textY - padding, width: textWidth + padding * 2, height: textHeight + padding * 2 },
            null,
            new Color(255, 255, 255, 96)
        );

        const textColor = new Color(24, 36, 55, 255);
        for (let i = 0; i < textUpper.length; i++) {
            const char = textUpper[i];
            const rows = this.GLYPHS[char] || this.GLYPHS['?'] || [0x0e, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04];
            const charX = textX + i * 6 * pixelSize;

            for (let row = 0; row < 7; row++) {
                const rowData = rows[row];
                for (let col = 0; col < 5; col++) {
                    if ((rowData & (1 << (4 - col))) !== 0) {
                        spriteBatch.draw(
                            solidTexture,
                            { x: charX + col * pixelSize, y: textY + row * pixelSize, width: pixelSize, height: pixelSize },
                            null,
                            textColor
                        );
                    }
                }
            }
        }
    }
